export type MessageKey = { [N in keyof typeof uz]: `${N}.${keyof typeof uz[N] & string}` }[keyof typeof uz];
export function message(language: 'uz' | 'ru', key: MessageKey): string {
  const [namespace, name] = key.split('.') as [keyof typeof uz, string];
  return (language === 'ru' ? ru : uz)[namespace][name as never];
}

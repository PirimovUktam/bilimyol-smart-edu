export type Translated<T> = { [K in keyof T]: T[K] extends string ? string : Translated<T[K]> };
export type MessageKey = { [N in keyof typeof uz]: `${N}.${keyof typeof uz[N] & string}` }[keyof typeof uz];
let russian: Translated<typeof uz> | undefined;
let loading: Promise<void> | undefined;

export function loadRussian(): Promise<void> {
  return loading ??= import('./messages.ru').then(({ ru }) => { russian = ru; }).catch((error: unknown) => {
    loading = undefined;
    throw error;
  });
}

export function message(language: 'uz' | 'ru', key: MessageKey): string {
  const [namespace, name] = key.split('.') as [keyof typeof uz, string];
  return (language === 'ru' ? russian ?? uz : uz)[namespace][name as never];
}

LessonStep _permuteStepQuestions(LessonStep step) {
  final question = step.interactiveQuestion;
  if (question == null) return step;
  return LessonStep(
    id: step.id,
    stepNumber: step.stepNumber,
    type: step.type,
    title: step.title,
    titleRu: step.titleRu,
    subtitle: step.subtitle,
    subtitleRu: step.subtitleRu,
    content: step.content,
    contentRu: step.contentRu,
    highlightNotes: step.highlightNotes,
    highlightNotesRu: step.highlightNotesRu,
    masteryCheckpoint: step.masteryCheckpoint,
    formulaData: step.formulaData,
    visualModelData: step.visualModelData,
    media: step.media,
    flashcards: step.flashcards,
    interactiveQuestion: permuteQuestionOptions(question),
  );
}

Lesson _permuteLessonQuestions(Lesson lesson) {
  return Lesson(
    id: lesson.id,
    courseId: lesson.courseId,
    skillId: lesson.skillId,
    skillDomain: lesson.skillDomain,
    communicativeFocus: lesson.communicativeFocus,
    cefrLevel: lesson.cefrLevel,
    moduleId: lesson.moduleId,
    unitId: lesson.unitId,
    canDoObjective: lesson.canDoObjective,
    canDoObjectiveRu: lesson.canDoObjectiveRu,
    prerequisites: lesson.prerequisites,
    title: lesson.title,
    titleRu: lesson.titleRu,
    estimatedMinutes: lesson.estimatedMinutes,
    summary: lesson.summary,
    summaryRu: lesson.summaryRu,
    officialCefrDisclaimerUz: lesson.officialCefrDisclaimerUz,
    officialCefrDisclaimerRu: lesson.officialCefrDisclaimerRu,
    steps: lesson.steps.map(_permuteStepQuestions).toList(growable: false),
    reinforcementExercise: permuteQuestionOptions(lesson.reinforcementExercise),
    alternateExercise: lesson.alternateExercise != null
        ? permuteQuestionOptions(lesson.alternateExercise!)
        : null,
    requiresMastery: lesson.requiresMastery,
  );
}


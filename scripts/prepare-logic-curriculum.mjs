import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';

const file = (path) => new URL('../' + path, import.meta.url);
const curriculum = JSON.parse(readFileSync(file('content/logic/curriculum.json'), 'utf8'));
const courseId = 'course_logic';
const minutes = 7;
const checking = process.argv.includes('--check');

function output(path, text) {
  if (checking) assert.equal(readFileSync(file(path), 'utf8').replaceAll('\r\n', '\n'), text, path);
  else writeFileSync(file(path), text);
}

assert.equal(curriculum.stages.length, 6);
assert.equal(curriculum.lessons.length, 12);
assert.equal(new Set(curriculum.lessons.map((lesson) => lesson.id)).size, 12);
assert.equal(new Set(curriculum.lessons.map((lesson) => lesson.node)).size, 12);

const lessons = curriculum.lessons.map((lesson, index) => {
  const { id, skill: skillId, title, hook, example } = lesson;
  const stage = curriculum.stages[lesson.stage - 1];
  assert.equal(lesson.stage, Math.floor(index / 2) + 1);
  assert.equal(lesson.checks.length, 3);
  const check = (position) => {
    const [text, correctIndex, explanation] = lesson.checks[position];
    assert([0, 1, 2].includes(correctIndex) && text.every((value) => /A\).+B\).+C\)/u.test(value)));
    return {
      id: 'q_' + id + '_v2_' + (position + 1),
      courseId, skillId, text: text[0], textRu: text[1],
      options: ['A', 'B', 'C'], correctIndex, difficulty: index < 4 ? 'easy' : 'medium',
      explanation: explanation[0], explanationRu: explanation[1],
    };
  };
  const step = (stepNumber, type, name, content, extras = {}) => ({
    id: id + '_v2_step_' + stepNumber, stepNumber, type, title: name[0], titleRu: name[1],
    content: content[0], contentRu: content[1], ...extras,
  });
  const media = index % 2 === 0 ? {
    id: 'logic_' + stage.diagram, kind: 'image', reviewStatus: 'approved', language: 'uz',
    title: stage.uz, titleRu: stage.ru, source: '/lesson-media/logic/' + stage.diagram + '.png',
    alt: example[0], altRu: example[1],
  } : undefined;
  return {
    id, courseId, skillId, title: title[0], titleRu: title[1],
    summary: hook[0], summaryRu: hook[1], estimatedMinutes: minutes,
    steps: [
      step(1, 'concept', ['Vaziyat', 'Ситуация'], hook),
      step(2, 'visual_example', ['Işlangan misol', 'Разбор примера'], example, media ? { media } : {}),
      step(3, 'interactive_question', ['Birinçi uriniş', 'Первая попытка'], ['Variantni tanlang.', 'Выберите вариант.'], { interactiveQuestion: check(0) }),
      step(4, 'interactive_question', ['Yangi vaziyat', 'Новая ситуация'], ['Qoidani yangi misolga qöllang.', 'Примените правило в новом примере.'], { interactiveQuestion: check(1) }),
    ],
    reinforcementExercise: check(2),
  };
});

const roadmap = lessons.map((lesson, index) => {
  const { node: id, stage } = curriculum.lessons[index];
  const group = curriculum.stages[stage - 1];
  return {
    id, courseId, skillId: lesson.skillId,
    title: stage + '. ' + group.uz + ' · ' + lesson.title,
    titleRu: stage + '. ' + group.ru + ' · ' + lesson.titleRu,
    description: lesson.summary, descriptionRu: lesson.summaryRu,
    prerequisites: index ? [curriculum.lessons[index - 1].node] : [],
    targetLessonId: lesson.id, estimatedMinutes: minutes, order: index + 1,
    requiredScore: 50, status: index ? 'locked' : 'available', isReinforcement: false,
  };
});

const jsonRows = (rows) => rows.map((row) => '    ' + JSON.stringify(row)).join(',\n');
output('content/logic/published.json', '{\n  "lessons": [\n' + jsonRows(lessons)
  + '\n  ],\n  "roadmap": [\n' + jsonRows(roadmap) + '\n  ]\n}\n');


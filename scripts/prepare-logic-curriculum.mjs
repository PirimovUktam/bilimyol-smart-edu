const dartString = (value) => JSON.stringify(value).replaceAll('$', '\\$');
const fields = (object) => Object.entries(object).map(([key, value]) => key + ': ' + dartValue(key, value)).join(', ');
function dartValue(key, value) {
  if (key === 'steps') return '[' + value.map((step) => 'LessonStep(' + fields(step) + ')').join(', ') + ']';
  if (key === 'type') return 'LessonStepType.' + ({ visual_example: 'visualExample', interactive_question: 'interactiveQuestion' }[value] ?? value);
  if (key === 'status') return 'NodeStatus.' + value;
  if (key === 'difficulty') return 'QuestionDifficulty.' + value;
  if (key === 'media') {
    const { kind, language, reviewStatus, ...text } = value;
    return 'LessonMedia(kind: LessonMediaKind.image, language: LessonMediaLanguage.uz, ' + fields(text) + ')';
  }
  if (key === 'interactiveQuestion' || key === 'reinforcementExercise') return 'Question(' + fields(value) + ')';
  if (Array.isArray(value)) return '[' + value.map(dartString).join(', ') + ']';
  return typeof value === 'string' ? dartString(value) : String(value);
}

